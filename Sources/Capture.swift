import AppKit

/// Polls the system clipboard and records every change, including Universal Clipboard copies from iPhone.
final class Capture {
    private let db = DB()
    private let queue = DispatchQueue(label: "clipbubble.capture")
    private var count = NSPasteboard.general.changeCount
    private var seenCount = NSPasteboard.general.changeCount
    private var seenAt = Date()
    /// The latest capture and the one before it, to spot tools that paste through the clipboard.
    private var last: (hash: String, at: Date, inserted: Bool)?
    private var previousHash: String?
    private var timer: DispatchSourceTimer?
    private let onChange: () -> Void

    /// The pasteboard change sync made when it put another device's copy there. Capturing it again would bounce it back.
    private static let skipLock = NSLock()
    private static var skipCount = -1
    static func ignoreChange(_ changeCount: Int) { skipLock.lock(); skipCount = changeCount; skipLock.unlock() }
    private static func isSyncWrite(_ changeCount: Int) -> Bool { skipLock.lock(); defer { skipLock.unlock() }; return changeCount == skipCount }

    /// Password managers and other tools mark secrets and throwaway copies with these; never record them.
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
    ]
    /// Text bigger than this (a log dump, a database export) isn't kept: it would slow every list and search.

    init(onChange: @escaping () -> Void) {
        self.onChange = onChange
        let t = DispatchSource.makeTimerSource(queue: queue)
        t.schedule(deadline: .now(), repeating: 0.4)
        t.setEventHandler { [weak self] in self?.poll() }
        t.resume()
        timer = t
    }

    private func poll() {
        let pb = NSPasteboard.general
        let now = Date()
        // Let the clipboard settle first. Paste-through tools like Wispr Flow put text on it, press ⌘V and then
        // restore the old contents; reading during that window could make them paste the wrong thing.
        if pb.changeCount != seenCount { seenCount = pb.changeCount; seenAt = now; return }
        guard seenCount != count, now.timeIntervalSince(seenAt) >= 0.6 else { return }
        count = seenCount
        // Sync replaced the last copy, so copying that again is a new copy.
        if Self.isSyncWrite(count) { last = nil; previousHash = nil; return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard !types.isEmpty, types.isDisjoint(with: Self.skipTypes), let clip = read(pb) else { return }
        // The same copy again is a no-op, unless it was deleted from history in between.
        if clip.hash == last?.hash, db.exists(hash: clip.hash) { return }
        let source = types.contains("com.apple.is-remote-clipboard")
            ? "iPhone" : (NSWorkspace.shared.frontmostApplication?.localizedName ?? "Mac")
        let category = source == "iPhone" ? "iphone" : (["image": "images", "file": "files"][clip.kind] ?? "text")
        guard Prefs.on(category) else { return }

        // The previous contents came straight back, so what we just saw was a paste-through: drop it,
        // and don't bump the restored item.
        if clip.hash == previousHash, let l = last, now.timeIntervalSince(l.at) < 2.5 {
            if l.inserted { db.delete(hash: l.hash) }
            last = (clip.hash, now, false)
            previousHash = nil
            onChange()
            return
        }

        if let png = clip.png, let path = clip.file, !FileManager.default.fileExists(atPath: path) {
            FileManager.default.createFile(atPath: path, contents: png)
        }
        let inserted = !db.exists(hash: clip.hash)
        db.upsert(kind: clip.kind, text: clip.text, file: clip.file, source: source, hash: clip.hash)
        previousHash = last?.hash
        last = (clip.hash, now, inserted)
        onChange()
    }

    /// What's on the clipboard. An image isn't written anywhere yet: Copied images might be off.
    private func read(_ pb: NSPasteboard) -> (kind: String, text: String, file: String?, hash: String, png: Data?)? {
        let string = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines)
        let looksLikeURL = string.map { !$0.contains(" ") && !$0.contains("\n") && $0.hasPrefix("http") } ?? false

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            return ("file", paths, nil, "f:" + sha(paths), nil)
        }
        if string?.isEmpty ?? true || looksLikeURL, let png = imagePNG(pb) {
            let h = sha(png)
            return ("image", "", Paths.images.appendingPathComponent(h + ".png").path, "i:" + h, png)
        }
        if let raw = pb.string(forType: .string), !(string?.isEmpty ?? true), raw.utf8.count <= Sync.maxText {
            return ("text", raw, nil, "t:" + sha(raw), nil)
        }
        return nil
    }

    private func imagePNG(_ pb: NSPasteboard) -> Data? {
        if let d = pb.data(forType: .png) { return d }
        for t in [NSPasteboard.PasteboardType.tiff, .init("public.jpeg"), .init("public.heic")] {
            if let d = pb.data(forType: t), let rep = NSBitmapImageRep(data: d) {
                return rep.representation(using: .png, properties: [:])
            }
        }
        return nil
    }
}

/// Watches a folder (screenshots, Downloads) and hands each new item that passes `include` to `onNew`.
final class FolderWatcher {
    static let tempExts: Set<String> = ["crdownload", "download", "part", "partial", "tmp", "opdownload", "icloud"]
    /// Where macOS saves screenshots (⌘⇧5 → Options → Save to), or the Desktop if that's never been set.
    static var macOSScreenshotFolder: URL {
        let raw = UserDefaults(suiteName: "com.apple.screencapture")?.string(forKey: "location") ?? "~/Desktop"
        return URL(fileURLWithPath: (raw as NSString).expandingTildeInPath, isDirectory: true)
    }
    /// A folder picked in Settings wins over the macOS setting.
    static var screenshotFolder: URL {
        if let custom = UserDefaults.standard.string(forKey: "screenshotFolder"), !custom.isEmpty {
            return URL(fileURLWithPath: custom, isDirectory: true)
        }
        return macOSScreenshotFolder
    }
    static var downloadsFolder: URL? { FileManager.default.urls(for: .downloadsDirectory, in: .userDomainMask).first }

    static func isScreenCapture(_ url: URL) -> Bool {
        getxattr(url.path, "com.apple.metadata:kMDItemIsScreenCapture", nil, 0, 0, 0) >= 0
    }

    /// Whether we can read the folder (asks macOS the first time, which may show its privacy prompt).
    static func canRead(_ url: URL?) -> Bool {
        guard let url else { return false }
        return (try? FileManager.default.contentsOfDirectory(atPath: url.path)) != nil
    }

    let folder: URL
    private let include: (URL) -> Bool
    private let maxAge: TimeInterval?
    private let onNew: (URL, Date) -> Void
    private var known: Set<URL> = []
    private var source: DispatchSourceFileSystemObject?
    private var pending: DispatchWorkItem?
    private var stopped = false

    /// `maxAge` ignores files older than that (so moving old screenshots in doesn't count); nil takes everything new.
    init(folder: URL, maxAge: TimeInterval?, include: @escaping (URL) -> Bool, onNew: @escaping (URL, Date) -> Void) {
        self.folder = folder
        self.maxAge = maxAge
        self.include = include
        self.onNew = onNew
        known = Set(listing())
        start()
    }

    func stop() {
        stopped = true
        source?.cancel()
        source = nil
    }

    /// Retries until macOS grants access to the folder (the privacy prompt may still be open).
    private func start() {
        guard !stopped else { return }
        let fd = open(folder.path, O_EVTONLY)
        guard fd >= 0 else {
            DispatchQueue.main.asyncAfter(deadline: .now() + 5) { [weak self] in self?.start() }
            return
        }
        known = Set(listing())
        let src = DispatchSource.makeFileSystemObjectSource(fileDescriptor: fd, eventMask: [.write, .rename, .delete], queue: .main)
        src.setEventHandler { [weak self, weak src] in
            guard let self, let src else { return }
            // The folder itself moved or vanished: the old handle is dead, so watch the path afresh.
            if !src.data.isDisjoint(with: [.rename, .delete]) {
                src.cancel()
                self.source = nil
                DispatchQueue.main.asyncAfter(deadline: .now() + 1) { [weak self] in self?.start() }
                return
            }
            self.pending?.cancel()
            let w = DispatchWorkItem { self.scan() }
            self.pending = w
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.4, execute: w)
        }
        src.setCancelHandler { close(fd) }
        src.resume()
        source = src
    }

    static func added(_ u: URL) -> Date {
        let v = try? u.resourceValues(forKeys: [.addedToDirectoryDateKey, .creationDateKey])
        return v?.addedToDirectoryDate ?? v?.creationDate ?? .distantPast
    }

    /// Everything already in the folder from the last `days` days, for backfilling history.
    func existing(days: Double) -> [(URL, Date)] {
        let cutoff = Date().addingTimeInterval(-days * 86400)
        return listing().map { ($0, Self.added($0)) }.filter { $0.1 > cutoff }
    }

    private func listing() -> [URL] {
        let urls = (try? FileManager.default.contentsOfDirectory(
            at: folder, includingPropertiesForKeys: [.creationDateKey, .addedToDirectoryDateKey], options: [.skipsHiddenFiles])) ?? []
        return urls.filter(include)
    }

    private func scan() {
        let now = listing()
        let fresh = now.filter { !known.contains($0) }
        known = Set(now)
        let cutoff = maxAge.map { Date().addingTimeInterval(-$0) }
        for url in fresh.sorted(by: { Self.added($0) < Self.added($1) }) {
            let date = Self.added(url)
            if let cutoff, date < cutoff { continue }
            onNew(url, maxAge == nil ? Date() : date)
        }
    }
}
